CREATE DATABASE IF NOT EXISTS subscription_db;
USE subscription_db;

CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL,
 email VARCHAR(150) UNIQUE NOT NULL, password_hash CHAR(64) NOT NULL,
 role ENUM('ADMIN','BILLING','CUSTOMER') NOT NULL DEFAULT 'CUSTOMER',
 phone VARCHAR(25), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS plans (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, description TEXT,
 price DECIMAL(10,2) NOT NULL, billing_cycle ENUM('MONTHLY','QUARTERLY','YEARLY') NOT NULL,
 status ENUM('ACTIVE','INACTIVE') DEFAULT 'ACTIVE'
);
CREATE TABLE IF NOT EXISTS subscriptions (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, plan_id INT NOT NULL,
 start_date DATE NOT NULL, next_billing_date DATE NOT NULL,
 status ENUM('ACTIVE','CANCELLED','EXPIRED') DEFAULT 'ACTIVE',
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(plan_id) REFERENCES plans(id)
);
CREATE TABLE IF NOT EXISTS invoices (
 id INT AUTO_INCREMENT PRIMARY KEY, subscription_id INT NOT NULL,
 invoice_date DATE NOT NULL, due_date DATE NOT NULL, amount DECIMAL(10,2) NOT NULL,
 status ENUM('UNPAID','PAID','OVERDUE') DEFAULT 'UNPAID',
 FOREIGN KEY(subscription_id) REFERENCES subscriptions(id)
);
CREATE TABLE IF NOT EXISTS payments (
 id INT AUTO_INCREMENT PRIMARY KEY, invoice_id INT NOT NULL, amount DECIMAL(10,2) NOT NULL,
 payment_method ENUM('CASH','CARD','UPI','BANK_TRANSFER') NOT NULL,
 transaction_ref VARCHAR(100), payment_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 status ENUM('SUCCESS','FAILED') DEFAULT 'SUCCESS',
 FOREIGN KEY(invoice_id) REFERENCES invoices(id)
);
